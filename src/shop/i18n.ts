import { useEffect, useState } from 'react'

export type Lang = 'he' | 'en'
const KEY = 'bs_lang'
let lang: Lang = (() => { try { return (localStorage.getItem(KEY) as Lang) || 'he' } catch { return 'he' } })()
const listeners = new Set<() => void>()
export function getLang() { return lang }
export function setLang(l: Lang) { lang = l; try { localStorage.setItem(KEY, l) } catch { /* ignore */ } applyDir(); listeners.forEach(f => f()) }
export function applyDir() { document.documentElement.lang = lang; document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr' }
export function useLang() {
  const [, tick] = useState(0)
  useEffect(() => { const f = () => tick(t => t + 1); listeners.add(f); return () => { listeners.delete(f) } }, [])
  return lang
}

